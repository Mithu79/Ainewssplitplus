export const DICTIONARIES: Record<Locale, Dictionary> = { en, bn, hi, ta };

export function getDictionary(locale: Locale): Dictionary {
  return DICTIONARIES[locale] ?? en;
}

/** Tiny `{placeholder}` interpolation helper. */
export function t(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );
}

/** Flattens a dictionary into dotted keys — used by the tests to compare coverage. */
export function flattenDictionary(dict: Dictionary, prefix = ""): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(dict as Record<string, unknown>)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") out[path] = value;
    else if (value && typeof value === "object") Object.assign(out, flattenDictionary(value as Dictionary, path));
  }
  return out;
}
